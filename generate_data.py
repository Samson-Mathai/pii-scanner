def generate_kenyan_name() -> str:
    return f"{random.choice(KENYAN_FIRST_NAMES)} {random.choice(KENYAN_LAST_NAMES)}"


def generate_phone() -> str:
    prefixes = ["0701", "0712", "0722", "0724", "0733", "0790", "0110", "0112"]
    choice = random.choice([1, 2, 3])
    p = random.choice(prefixes)
    rest = f"{random.randint(100000, 999999)}"
    if choice == 1:
        return f"+254 {p[1:]} {rest[:3]} {rest[3:]}"
    elif choice == 2:
        return f"{p}-{rest[:3]}-{rest[3:]}"
    return f"{p}{rest}"


def generate_national_id() -> str:
    # Kenyan national IDs are 7 or 8 digits
    return str(random.randint(11000000, 39999999))


def generate_kra_pin() -> str:
    first_letter = random.choice(["A", "P"])
    digits = f"{random.randint(100000000, 999999999)}"
    last_letter = random.choice(["X", "Z", "W", "K", "Y"])
    return f"{first_letter}{digits}{last_letter}"


def generate_mpesa_code() -> str:
    letters = "ABCDEFGHJKLMNPQRSTUVWXYZ"
    digits = "0123456789"
    # M-Pesa format: 10 chars, typically 2-3 letters prefix then mix
    prefix = "".join(random.choice(letters) for _ in range(2))
    mix = "".join(random.choice(letters + digits) for _ in range(8))
    return f"{prefix}{mix}"


def generate_bank_account() -> str:
    # 10 to 14 digits
    return str(random.randint(1000000000, 999999999999))


def create_customers_csv(target_path: str):
    fieldnames = [
        "Customer_ID", "Full_Name", "National_ID_No", "Phone_Number",
        "KRA_PIN", "Email_Address", "Bank_Account_Number", "County"
    ]
    with open(target_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for i in range(1, 26):
            name = generate_kenyan_name()
            username = name.lower().replace(" ", ".")
            writer.writerow({
                "Customer_ID": f"CUST-{1000 + i}",
                "Full_Name": name,
                "National_ID_No": f"ID No: {generate_national_id()}",
                "Phone_Number": generate_phone(),
                "KRA_PIN": generate_kra_pin(),
                "Email_Address": f"{username}@{fake.free_email_domain()}",
                "Bank_Account_Number": f"A/C {generate_bank_account()}",
                "County": random.choice(KENYAN_COUNTIES),
            })


def create_employee_salaries_csv(target_path: str):
    fieldnames = [
        "Staff_ID", "Employee_Name", "National_ID", "Department",
        "Basic_Salary_KES", "Allowances_KES", "Net_Pay_KES", "KRA_PIN"
    ]
    with open(target_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for i in range(1, 16):
            basic = random.randint(65000, 320000)
            allowances = int(basic * 0.18)
            net_pay = int((basic + allowances) * 0.72)
            writer.writerow({
                "Staff_ID": f"EMP-{500 + i}",
                "Employee_Name": generate_kenyan_name(),
                "National_ID": f"National ID: {generate_national_id()}",
                "Department": random.choice(DEPARTMENTS),
                "Basic_Salary_KES": f"{basic:,}",
                "Allowances_KES": f"{allowances:,}",
                "Net_Pay_KES": f"{net_pay:,}",
                "KRA_PIN": generate_kra_pin(),
            })


def create_mpesa_messages_txt(target_path: str):
    messages = []
    for _ in range(10):
        code = generate_mpesa_code()
        amount = random.randint(500, 65000)
        phone = generate_phone()
        name = generate_kenyan_name().upper()
        balance = random.randint(1500, 150000)
        cost = random.choice([0, 12, 23, 45, 68, 105])
        msg = (
            f"{code} Confirmed. Ksh {amount:,.2f} sent to {name} {phone} "
            f"on 28/10/2026 at 14:32. New M-PESA balance is Ksh {balance:,.2f}. "
            f"Transaction cost, Ksh {cost:.2f}. Lipa na M-PESA."
        )
        messages.append(msg)

    with open(target_path, "w", encoding="utf-8") as f:
        f.write("\n\n".join(messages))


